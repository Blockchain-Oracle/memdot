// Copies the registry ABI from Foundry's build output into src/abi.ts (run after `forge build`).
import { readFile, writeFile } from "node:fs/promises";

const artifact = JSON.parse(
  await readFile(new URL("../out/MemDotRegistry.sol/MemDotRegistry.json", import.meta.url), "utf8"),
) as { abi: unknown[] };

const source = `// Generated by scripts/export-abi.ts from the Foundry build. Do not edit.
export const memDotRegistryAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;
await writeFile(new URL("../src/abi.ts", import.meta.url), source);
console.log(`Wrote src/abi.ts (${artifact.abi.length} entries)`);
