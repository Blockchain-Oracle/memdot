"""Connected agents.

A device asks with `start_connect` and collects with `poll_connect`; the owner, unlocked elsewhere,
types its code into `claim_connect` and answers with `approve_connect`, which wraps each chosen
space's keys to the device's public key. A hosted agent holds no key, so it is allowed with
`allow_hosted` and reaches Assisted namespaces only.
"""

from __future__ import annotations

import base64
import contextlib
import re
from datetime import datetime, timedelta, timezone
from typing import Any

from .. import crypto
from ..errors import MemDotError
from ..models import Agent, ConnectRequest, ConnectResult, ConnectStart
from .context import AsyncContext
from .sharing import AsyncSharing
from .transport import seg

#: Keys are generated by the API from this alphabet, and go into shell files as they are.
API_KEY_FORMAT = re.compile(r"md_[A-Za-z0-9_-]+")


class AsyncAgents:
    def __init__(self, ctx: AsyncContext, sharing: AsyncSharing) -> None:
        self._ctx = ctx
        self._sharing = sharing

    async def list(self) -> list[Agent]:
        page = await self._ctx.transport.json("GET", "/v1/agents")
        return [Agent.model_validate(item) for item in page["items"]]

    async def rename(self, agent_id: str, label: str) -> Agent:
        return Agent.model_validate(
            await self._ctx.transport.json("PATCH", f"/v1/agents/{seg(agent_id)}", {"label": label})
        )

    async def revoke(self, agent: Agent) -> Any:
        """Stops its keys and tokens at once, and moves the spaces it held to a new key epoch."""
        revoked = await self._ctx.transport.json("DELETE", f"/v1/agents/{seg(agent.id)}")
        if agent.public_key:
            await self._ctx.registry.revoke_agent(agent.public_key)
        return revoked

    # ── On the device ────────────────────────────────────────────────────────────────────────

    async def start_connect(self, *, public_key: str, label: str, client: str) -> ConnectStart:
        return ConnectStart.model_validate(
            await self._ctx.transport.json(
                "POST", "/v1/connect", {"publicKey": public_key, "label": label, "client": client}
            )
        )

    async def poll_connect(self, connect_id: str, poll_secret: str, identity: str) -> ConnectResult:
        result = await self._ctx.transport.json(
            "POST", f"/v1/connect/{seg(connect_id)}/poll", {"pollSecret": poll_secret}
        )
        api_key = (
            crypto.open_with(
                base64.b64decode(result["sealedKey"]), identity, "the connection"
            ).decode()
            if result.get("sealedKey")
            else None
        )
        # Anyone can seal to a public key, and this is about to be written into settings files.
        if api_key and not API_KEY_FORMAT.fullmatch(api_key):
            raise MemDotError(502, "BAD_KEY", "What came back doesn't look like a MemDot key.")
        return ConnectResult(
            status=result["status"],
            api_key=api_key,
            agent_id=result.get("agentId"),
            namespace_id=result.get("namespaceId"),
            owner_account=result.get("ownerAccount"),
        )

    # ── On the owner's side ──────────────────────────────────────────────────────────────────

    async def claim_connect(self, connect_id: str, code: str) -> ConnectRequest:
        """Takes the request for this account, with the code its terminal shows."""
        return ConnectRequest.model_validate(
            await self._ctx.transport.json(
                "POST", f"/v1/connect/{seg(connect_id)}/claim", {"code": code}
            )
        )

    async def deny_connect(self, connect_id: str) -> Any:
        return await self._ctx.transport.json("POST", f"/v1/connect/{seg(connect_id)}/deny")

    async def approve_connect(
        self,
        request: ConnectRequest,
        *,
        space_ids: list[str],
        role: str,
        namespace_id: str | None = None,
        expires_in_days: int | None = None,
    ) -> Agent:
        """Registers the agent, wraps each space's keys to it, then lets the device collect its key.

        Safe to call again if it stops part way: what's already done is left alone. If it can't
        finish, an agent made by this call doesn't stay behind holding keys.
        """
        agent, created = await self._registered(request)
        try:
            expires_at = None
            if expires_in_days:
                moment = datetime.now(timezone.utc) + timedelta(days=expires_in_days)
                expires_at = moment.strftime("%Y-%m-%dT%H:%M:%S.000Z")
            scope = "read_write" if role == "read_write" else "read"
            for space_id in space_ids:
                given = await self._sharing.list("given", space_id)
                if any(
                    grant.grantee == agent.public_key
                    and grant.status == "active"
                    and not grant.object_id
                    for grant in given
                ):
                    continue
                await self._sharing.share_space(
                    space_id,
                    {"agent_id": agent.id, "agent_key": request.public_key},
                    scope=scope,
                    expires_at=expires_at,
                )
            body: dict[str, Any] = {"agentId": agent.id, "spaceIds": space_ids, "role": role}
            if namespace_id:
                body["namespaceId"] = namespace_id
            if expires_in_days:
                body["expiresInDays"] = expires_in_days
            await self._ctx.transport.json("POST", f"/v1/connect/{seg(request.id)}/approve", body)
            return agent
        except Exception:
            if created:
                with contextlib.suppress(MemDotError):
                    await self.revoke(agent)
            raise

    async def _registered(self, request: ConnectRequest) -> tuple[Agent, bool]:
        try:
            agent = Agent.model_validate(
                await self._ctx.transport.json(
                    "POST",
                    "/v1/agents",
                    {
                        "label": request.label,
                        "client": request.client,
                        "publicKey": request.public_key,
                    },
                )
            )
            await self._ctx.registry.register_agent(request.public_key)
            return agent, True
        except MemDotError as error:
            if error.code != "AGENT_KEY_TAKEN":
                raise
            for candidate in await self.list():
                if candidate.public_key == request.public_key and not candidate.revoked_at:
                    return candidate, False
            raise
